<#
.SYNOPSIS
Forward MCP stdio traffic with session-local tool discovery before tool calls.
.DESCRIPTION
Internal runtime helper copied into generated skills. Accepts the server
executable followed by its arguments verbatim (intentionally no parameter
binding). Only JSON-RPC messages are written to stdout. Diagnostics use stderr.
The caller's environment and working directory are inherited.
.EXAMPLE
pwsh -NoProfile -File .\scripts\Invoke-McpStdioBridge.ps1 node C:\tools\server.js
Used by generated MCP CLI configuration, not as an agent-facing tool.
.NOTES
The skill copy is generated by the toolkit build pipeline and is
overwritten when the skill package is regenerated.
Do not edit this file directly in generated skills; edit the toolkit source.
Requires PowerShell 7. Discovery uses MCP_TIMEOUT in seconds (default 1800).
Tool calls are never replayed. The owned server process is stopped on disconnect.
#>
$ErrorActionPreference = 'Stop'
$utf8 = [Text.UTF8Encoding]::new($false)
[Console]::InputEncoding = $utf8
[Console]::OutputEncoding = $utf8
$OutputEncoding = $utf8
$server = $null
$serverStarted = $false
$exitCode = 1

try {
    # PowerShell handles Windows command shims and script entry points without
    # constructing a cmd.exe command string from executable configuration.
    if ($args.Count -gt 1 -and $args[0] -ceq '--execute-server') {
        $command = $args[1]
        $commandArguments = @($args | Select-Object -Skip 2)
        $LASTEXITCODE = 0
        $PSNativeCommandUseErrorActionPreference = $false
        & $command @commandArguments
        exit $LASTEXITCODE
    }
    if ($args.Count -eq 0 -or [string]::IsNullOrWhiteSpace($args[0])) {
        throw 'The MCP stdio bridge requires a server executable and its arguments.'
    }
    $startInfo = [Diagnostics.ProcessStartInfo]::new()
    $command = Get-Command -Name $args[0] -CommandType Application, ExternalScript -ErrorAction Stop | Select-Object -First 1
    $startInfo.FileName = $command.Source
    if ([IO.Path]::GetExtension($command.Source) -in @('.cmd', '.bat', '.ps1')) {
        $startInfo.FileName = Join-Path $PSHOME $(if ($IsWindows) { 'pwsh.exe' } else { 'pwsh' })
        foreach ($argument in @('-NoLogo', '-NoProfile', '-NonInteractive', '-File', $PSCommandPath, '--execute-server', $command.Source)) {
            $startInfo.ArgumentList.Add($argument)
        }
    }
    for ($index = 1; $index -lt $args.Count; $index++) {
        $startInfo.ArgumentList.Add($args[$index])
    }
    $startInfo.UseShellExecute = $false
    $startInfo.RedirectStandardInput = $true
    $startInfo.RedirectStandardOutput = $true
    $startInfo.RedirectStandardError = $true
    $startInfo.StandardInputEncoding = $utf8
    $startInfo.StandardOutputEncoding = $utf8
    $startInfo.StandardErrorEncoding = $utf8
    $server = [Diagnostics.Process]::new()
    $server.StartInfo = $startInfo
    [void]$server.Start()
    $serverStarted = $true
    $server.StandardInput.AutoFlush = $true

    # Console.In.ReadLineAsync can block synchronously; use the raw stream.
    $clientInput = [IO.StreamReader]::new([Console]::OpenStandardInput(), $utf8)
    $clientRead = $clientInput.ReadLineAsync()
    $serverRead = $server.StandardOutput.ReadLineAsync()
    $stderrBuffer = [char[]]::new(4096)
    $stderrRead = $server.StandardError.ReadAsync($stderrBuffer, 0, $stderrBuffer.Length)
    $ready = $false
    $inventoryVersion = 0
    $discoveryVersion = 0
    $discoveryId = $null
    $discoveryClock = [Diagnostics.Stopwatch]::new()
    $pendingCalls = [Collections.Generic.List[object]]::new()
    $cursors = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    $timeoutSeconds = 1800
    $configuredTimeout = 0
    if ([int]::TryParse($env:MCP_TIMEOUT, [ref]$configuredTimeout) -and $configuredTimeout -gt 0) {
        $timeoutSeconds = $configuredTimeout
    }

    while ($null -ne $serverRead -or $null -ne $stderrRead) {
        $tasks = [Collections.Generic.List[Threading.Tasks.Task]]::new()
        $tasks.Add($clientRead)
        if ($null -ne $serverRead) { $tasks.Add($serverRead) }
        if ($null -ne $stderrRead) { $tasks.Add($stderrRead) }
        $completed = [Threading.Tasks.Task]::WaitAny($tasks.ToArray(), 1000)
        if ($discoveryId -and $discoveryClock.Elapsed.TotalSeconds -ge $timeoutSeconds) {
            throw "MCP tool discovery timed out after $timeoutSeconds seconds; no queued tool calls were sent."
        }
        if ($completed -lt 0) { continue }

        $completedTask = $tasks[$completed]
        if ($completedTask -eq $clientRead) {
            $line = $clientRead.GetAwaiter().GetResult()
            if ($null -eq $line) { break }
            $clientRead = $clientInput.ReadLineAsync()
            $message = ConvertFrom-Json -InputObject $line -AsHashtable -Depth 100
            if ($message.method -eq 'tools/call' -and -not $ready) {
                if (-not $message.Contains('id')) {
                    throw 'A tools/call request must have a JSON-RPC id.'
                }
                $pendingCalls.Add(@{ Id = $message.id; Line = $line })
                if (-not $discoveryId) {
                    $discoveryId = 'mcp-skill-discovery-' + [Guid]::NewGuid().ToString('N')
                    $cursors.Clear()
                    $discoveryVersion = $inventoryVersion
                    $discoveryClock.Restart()
                    $request = @{ jsonrpc = '2.0'; id = $discoveryId; method = 'tools/list'; params = @{} }
                    $server.StandardInput.WriteLine(($request | ConvertTo-Json -Depth 100 -Compress))
                }
            }
            else {
                $server.StandardInput.WriteLine($line)
            }
        }
        elseif ($completedTask -eq $serverRead) {
            $line = $serverRead.GetAwaiter().GetResult()
            if ($null -eq $line) {
                $serverRead = $null
                continue
            }
            $serverRead = $server.StandardOutput.ReadLineAsync()
            $message = ConvertFrom-Json -InputObject $line -AsHashtable -Depth 100
            if ($discoveryId -and $message.Contains('id') -and $message.id -ceq $discoveryId) {
                $failure = $null
                if ($message.Contains('error')) {
                    $failure = "MCP tool discovery failed; no queued tool calls were sent: $($message.error.message)"
                }
                elseif (-not ($message.result -is [Collections.IDictionary]) -or
                    -not ($message.result.tools -is [System.Collections.IList])) {
                    $failure = 'MCP tool discovery returned an invalid tool list; no queued tool calls were sent.'
                }
                elseif ($message.result.Contains('nextCursor') -and $null -ne $message.result.nextCursor) {
                    $cursor = $message.result.nextCursor
                    if ($cursor -isnot [string] -or -not $cursors.Add($cursor)) {
                        $failure = 'MCP tool discovery returned an invalid or repeated cursor; no queued tool calls were sent.'
                    }
                    else {
                        $request = @{ jsonrpc = '2.0'; id = $discoveryId; method = 'tools/list'; params = @{ cursor = $cursor } }
                        $server.StandardInput.WriteLine(($request | ConvertTo-Json -Depth 100 -Compress))
                        continue
                    }
                }
                if ($failure) {
                    [Console]::Error.WriteLine($failure)
                    foreach ($call in $pendingCalls) {
                        $response = @{ jsonrpc = '2.0'; id = $call.Id; error = @{ code = -32603; message = $failure } }
                        [Console]::Out.WriteLine(($response | ConvertTo-Json -Depth 100 -Compress))
                    }
                }
                else {
                    if ($discoveryVersion -ne $inventoryVersion) {
                        $discoveryVersion = $inventoryVersion
                        $cursors.Clear()
                        $request = @{ jsonrpc = '2.0'; id = $discoveryId; method = 'tools/list'; params = @{} }
                        $server.StandardInput.WriteLine(($request | ConvertTo-Json -Depth 100 -Compress))
                        continue
                    }
                    $ready = $true
                    foreach ($call in $pendingCalls) {
                        $server.StandardInput.WriteLine($call.Line)
                    }
                }
                $pendingCalls.Clear()
                $discoveryId = $null
                $discoveryClock.Stop()
            }
            else {
                if ($message.method -eq 'notifications/tools/list_changed') {
                    $ready = $false
                    $inventoryVersion++
                }
                [Console]::Out.WriteLine($line)
            }
            [Console]::Out.Flush()
        }
        else {
            $count = $stderrRead.GetAwaiter().GetResult()
            if ($count -eq 0) {
                $stderrRead = $null
            }
            else {
                [Console]::Error.Write($stderrBuffer, 0, $count)
                [Console]::Error.Flush()
                $stderrRead = $server.StandardError.ReadAsync($stderrBuffer, 0, $stderrBuffer.Length)
            }
        }
    }
    if ($server.HasExited) {
        $exitCode = $server.ExitCode
    }
    else {
        $exitCode = 0
    }
}
catch {
    [Console]::Error.WriteLine("MCP stdio bridge failed: $($_.Exception.Message)")
}
finally {
    if ($null -ne $server) {
        if ($serverStarted -and -not $server.HasExited) {
            $server.StandardInput.Close()
            if (-not $server.WaitForExit(1000)) {
                $server.Kill($true)
                $server.WaitForExit()
            }
        }
        $server.Dispose()
    }
}
exit $exitCode
