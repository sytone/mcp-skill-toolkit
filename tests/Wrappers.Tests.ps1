Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

Describe 'Generated MCP wrapper runtime (offline)' {
    BeforeAll {
        $script:WrappersRepoRoot = Split-Path -Parent $PSScriptRoot
        $script:WrappersSource = Join-Path $script:WrappersRepoRoot 'psakefile.ps1'
        $script:WrappersRoot = Join-Path $script:WrappersRepoRoot ('.test-tmp/wrappers-' + [Guid]::NewGuid().ToString('N'))
        $script:WrappersPwsh = Join-Path $PSHOME 'pwsh.exe'
        $script:WrappersUtf8 = [Text.UTF8Encoding]::new($false)
        $script:WrappersServer = "offline server's 名称"
        New-Item -ItemType Directory -Path $script:WrappersRoot -Force | Out-Null

        # Do not dot-source the psake build or reconstruct its functions from text.
        # Original AST scriptblocks retain psakefile.ps1 file/line coverage locations.
        $parseTokens = $null
        $parseErrors = $null
        $sourceAst = [Management.Automation.Language.Parser]::ParseFile($script:WrappersSource, [ref]$parseTokens, [ref]$parseErrors)
        $parseErrors.Count | Should -Be 0
        $requiredFunctions = @(
            'Resolve-UserPath', 'ConvertTo-PowerShellSingleQuoted',
            'ConvertTo-PowerShellPathExpression', 'Get-AutoGeneratedToolScriptHeader',
            'Write-McpToolScripts'
        )
        $definitions = $sourceAst.FindAll({
            param($node)
            $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -in $requiredFunctions
        }, $false)
        $definitions.Count | Should -Be $requiredFunctions.Count
        foreach ($definition in $definitions) {
            Set-Item -Path ('Function:' + $definition.Name) -Value $definition.Body.GetScriptBlock()
        }
        (Get-Command Write-McpToolScripts).ScriptBlock.File | Should -Be $script:WrappersSource

        # Only this child process ever invokes generated scripts: they call exit.
        # JSON request files preserve typed named parameters without command-line
        # quoting or shell interpolation, including Unicode and apostrophes.
        $script:WrappersHarness = Join-Path $script:WrappersRoot 'invoke-generated.ps1'
        $harness = @'
param([string]$RequestPath)
$ErrorActionPreference = 'Stop'
[Console]::InputEncoding = [Text.UTF8Encoding]::new($false)
[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)
$request = Get-Content -LiteralPath $RequestPath -Raw -Encoding utf8 | ConvertFrom-Json -AsHashtable -Depth 100
$parameters = $request.Parameters
& $request.Script @parameters
exit $LASTEXITCODE
'@
        [IO.File]::WriteAllText($script:WrappersHarness, $harness, $script:WrappersUtf8)

        function New-WrapperScripts {
            param(
                [object[]]$ToolMetadata = @([pscustomobject]@{
                    Name = 'Search-Notes'
                    Parameters = @('Text', 'Count', 'Enabled', 'Items', 'Options', 'Tool', 'Json', 'JsonPath')
                }),
                [string]$CliPath = $script:WrappersFakeScript
            )

            Write-McpToolScripts -ScriptsDir $script:WrappersScripts -ServerName $script:WrappersServer -ConfigReference $script:WrappersConfig -McpCli $CliPath -ToolMetadata $ToolMetadata
        }

        function Invoke-WrapperProcess {
            param(
                [string]$ScriptName = 'Invoke-Tool.ps1',
                [hashtable]$Parameters = @{ Tool = 'Search-Notes' },
                [string]$Stdin = '',
                [int]$FakeExitCode = 0
            )

            $invocationRoot = Join-Path $script:WrappersCase ([Guid]::NewGuid().ToString('N'))
            New-Item -ItemType Directory -Path $invocationRoot | Out-Null
            $requestPath = Join-Path $invocationRoot 'request.json'
            $capturePath = Join-Path $invocationRoot 'cli-receipt.json'
            $request = @{
                Script = (Join-Path $script:WrappersScripts $ScriptName)
                Parameters = $Parameters
            } | ConvertTo-Json -Depth 100 -Compress
            [IO.File]::WriteAllText($requestPath, $request, $script:WrappersUtf8)

            $startInfo = [Diagnostics.ProcessStartInfo]::new()
            $startInfo.FileName = $script:WrappersPwsh
            $startInfo.UseShellExecute = $false
            $startInfo.CreateNoWindow = $true
            $startInfo.WorkingDirectory = $script:WrappersCase
            $startInfo.RedirectStandardInput = $true
            $startInfo.RedirectStandardOutput = $true
            $startInfo.RedirectStandardError = $true
            $startInfo.StandardInputEncoding = $script:WrappersUtf8
            $startInfo.StandardOutputEncoding = $script:WrappersUtf8
            $startInfo.StandardErrorEncoding = $script:WrappersUtf8
            foreach ($argument in @('-NoLogo', '-NoProfile', '-NonInteractive', '-File', $script:WrappersHarness, $requestPath)) {
                $startInfo.ArgumentList.Add($argument)
            }
            $startInfo.Environment['MCP_WRAPPER_CAPTURE_PATH'] = $capturePath
            $startInfo.Environment['MCP_WRAPPER_EXIT_CODE'] = [string]$FakeExitCode
            $startInfo.Environment['MCP_WRAPPER_INPUT_MODE'] = 'Pipeline'
            $startInfo.Environment['POWERSHELL_TELEMETRY_OPTOUT'] = '1'

            $child = [Diagnostics.Process]::new()
            $child.StartInfo = $startInfo
            try {
                $child.Start() | Should -BeTrue
                # Drain both streams asynchronously, so a failure cannot fill a
                # pipe and deadlock the Pester host. Close stdin even when empty.
                $stdoutTask = $child.StandardOutput.ReadToEndAsync()
                $stderrTask = $child.StandardError.ReadToEndAsync()
                $child.StandardInput.Write($Stdin)
                $child.StandardInput.Close()
                if (-not $child.WaitForExit(20000)) {
                    $child.Kill($true)
                    $child.WaitForExit()
                    throw "Generated wrapper '$ScriptName' exceeded its 20-second timeout."
                }
                $stdout = $stdoutTask.GetAwaiter().GetResult()
                $stderr = $stderrTask.GetAwaiter().GetResult()
                $receipt = if (Test-Path -LiteralPath $capturePath) {
                    Get-Content -LiteralPath $capturePath -Raw -Encoding utf8 | ConvertFrom-Json -AsHashtable -Depth 100
                }
                else {
                    $null
                }
                [pscustomobject]@{
                    ExitCode = $child.ExitCode
                    Stdout = $stdout
                    Stderr = $stderr
                    CapturePath = $capturePath
                    Receipt = $receipt
                }
            }
            finally {
                if ($child.Id -and -not $child.HasExited) {
                    $child.Kill($true)
                    $child.WaitForExit()
                }
                $child.Dispose()
            }
        }

        function Assert-WrapperReceipt {
            param($Result, [string]$Tool = 'Search-Notes')

            $Result.ExitCode | Should -Be 0 -Because $Result.Stderr
            $Result.Stderr | Should -BeNullOrEmpty
            $Result.Receipt | Should -Not -BeNullOrEmpty
            $Result.Receipt.ConfigPath | Should -Be $script:WrappersConfig
            $Result.Receipt.Command | Should -BeExactly 'call'
            $Result.Receipt.Server | Should -BeExactly $script:WrappersServer
            $Result.Receipt.Tool | Should -BeExactly $Tool
            @($Result.Receipt.ExtraArguments).Count | Should -Be 0
            # Check observable wrapper stdout too, not just the fake's disk marker.
            $printed = $Result.Stdout.Trim() | ConvertFrom-Json -AsHashtable -Depth 100
            $printed.Payload | Should -BeExactly $Result.Receipt.Payload
            $printed.Tool | Should -BeExactly $Tool
        }
    }

    BeforeEach {
        $script:WrappersCase = Join-Path $script:WrappersRoot ([Guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Path $script:WrappersCase | Out-Null
        $script:WrappersScripts = Join-Path $script:WrappersCase 'generated scripts'
        $script:WrappersConfig = Join-Path $script:WrappersCase "config with ' quote.json"
        $script:WrappersFakeScript = Join-Path $script:WrappersCase "fake cli's script.ps1"
        [IO.File]::WriteAllText($script:WrappersConfig, '{"servers":{}}', $script:WrappersUtf8)
        Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'fixtures/fake-mcp-cli.ps1') -Destination $script:WrappersFakeScript
        New-WrapperScripts
    }

    AfterAll {
        if ($script:WrappersRoot -and (Test-Path -LiteralPath $script:WrappersRoot)) {
            Remove-Item -LiteralPath $script:WrappersRoot -Recurse -Force -ErrorAction Stop
        }
    }

    It 'preserves Unicode, quotes, arrays, and nested JSON from <Source>' -ForEach @(
        @{ Source = 'Json' }
        @{ Source = 'JsonPath' }
        @{ Source = 'stdin' }
    ) {
        $payload = [ordered]@{
            Text = "Zażółć café 東京 😀 says `"hello`"; O'Brien; C:\notes\file"
            Items = @('first', 'quoted "item"', '雪')
            Empty = @()
            Single = @('only')
            Options = @{ Nested = @{ Enabled = $true; Count = 7; Value = $null }; Rows = @(@{ Id = 1 }, @{ Id = 2 }) }
        }
        $json = ConvertTo-Json -InputObject $payload -Depth 100
        $parameters = @{ Tool = 'Search-Notes' }
        $stdin = ''
        switch ($Source) {
            'Json' { $parameters.Json = $json }
            'JsonPath' {
                $jsonPath = Join-Path $script:WrappersCase "payload's Unicode 雪.json"
                [IO.File]::WriteAllText($jsonPath, $json, $script:WrappersUtf8)
                $parameters.JsonPath = $jsonPath
            }
            'stdin' { $stdin = $json }
        }

        $result = Invoke-WrapperProcess -Parameters $parameters -Stdin $stdin
        Assert-WrapperReceipt $result
        $actual = ConvertFrom-Json -InputObject $result.Receipt.Payload -AsHashtable -Depth 100
        $actual.Text | Should -BeExactly $payload.Text
        $actual.Items.Count | Should -Be 3
        $actual.Items[1] | Should -BeExactly 'quoted "item"'
        $actual.Items[2] | Should -BeExactly '雪'
        $actual.Empty.Count | Should -Be 0
        $actual.Single.Count | Should -Be 1
        $actual.Options.Nested.Enabled | Should -BeTrue
        $actual.Options.Nested.Count | Should -Be 7
        $actual.Options.Nested.Value | Should -BeNullOrEmpty
        $actual.Options.Rows.Count | Should -Be 2
        $actual.Options.Rows[1].Id | Should -Be 2
    }

    It 'preserves top-level JSON array shape: <JsonValue>' -ForEach @(
        @{ JsonValue = '[]' }
        @{ JsonValue = '[{"one":1}]' }
        @{ JsonValue = '[1,2]' }
    ) {
        $result = Invoke-WrapperProcess -Parameters @{ Tool = 'Search-Notes'; Json = $JsonValue }
        Assert-WrapperReceipt $result
        $result.Receipt.Payload | Should -BeExactly $JsonValue
    }

    It 'accepts stdin through a per-tool wrapper when no parameters were supplied' {
        $result = Invoke-WrapperProcess -ScriptName 'Search-Notes.ps1' -Parameters @{} -Stdin '{"stdin":"雪"}'
        Assert-WrapperReceipt $result
        (ConvertFrom-Json -InputObject $result.Receipt.Payload -AsHashtable).stdin | Should -BeExactly '雪'
    }

    It 'uses an empty object for <InputKind>' -ForEach @(
        @{ InputKind = 'omitted input' }
        @{ InputKind = 'whitespace stdin' }
        @{ InputKind = 'empty Json' }
    ) {
        $parameters = @{ Tool = 'Search-Notes' }
        $stdin = ''
        if ($InputKind -eq 'whitespace stdin') { $stdin = " `r`n`t " }
        if ($InputKind -eq 'empty Json') { $parameters.Json = '' }

        $result = Invoke-WrapperProcess -Parameters $parameters -Stdin $stdin
        Assert-WrapperReceipt $result
        $result.Receipt.Payload.Trim() | Should -BeExactly '{}'
    }

    It 'rejects mutually exclusive JSON inputs in <ScriptName> before calling the CLI' -ForEach @(
        @{ ScriptName = 'Invoke-Tool.ps1' }
        @{ ScriptName = 'Search-Notes.ps1' }
    ) {
        # A nonexistent file also proves the exclusivity check precedes file I/O.
        $parameters = @{ Json = '{}'; JsonPath = (Join-Path $script:WrappersCase 'does-not-exist.json') }
        if ($ScriptName -eq 'Invoke-Tool.ps1') { $parameters.Tool = 'Search-Notes' }

        $result = Invoke-WrapperProcess -ScriptName $ScriptName -Parameters $parameters
        $result.ExitCode | Should -Not -Be 0
        $result.Stderr | Should -Match 'Use only one of -Json or -JsonPath'
        Test-Path -LiteralPath $result.CapturePath | Should -BeFalse
        $result.Receipt | Should -BeNullOrEmpty
    }

    It 'rejects invalid JSON from <Source> before calling the CLI' -ForEach @(
        @{ Source = 'Json' }
        @{ Source = 'JsonPath' }
        @{ Source = 'stdin' }
    ) {
        $parameters = @{ Tool = 'Search-Notes' }
        $stdin = ''
        switch ($Source) {
            'Json' { $parameters.Json = '{"broken":' }
            'JsonPath' {
                $jsonPath = Join-Path $script:WrappersCase 'invalid.json'
                [IO.File]::WriteAllText($jsonPath, '{"broken":', $script:WrappersUtf8)
                $parameters.JsonPath = $jsonPath
            }
            'stdin' { $stdin = '{"broken":' }
        }

        $result = Invoke-WrapperProcess -Parameters $parameters -Stdin $stdin
        $result.ExitCode | Should -Not -Be 0
        $result.Stderr | Should -Match 'Invalid JSON payload for Search-Notes'
        Test-Path -LiteralPath $result.CapturePath | Should -BeFalse
        $result.Receipt | Should -BeNullOrEmpty
    }

    It 'propagates a <CliKind> fake CLI nonzero exit code through the per-tool wrapper' -ForEach @(
        @{ CliKind = 'script'; Code = 23 }
        @{ CliKind = 'native'; Code = 37 }
    ) {
        if ($CliKind -eq 'native') {
            # cmd.exe is the native process boundary; no compiler, installation,
            # executable search, or real mcp-cli executable is involved.
            $nativePath = Join-Path $script:WrappersCase 'fake native cli.cmd'
            $native = @(
                '@echo off'
                'setlocal'
                'set "MCP_WRAPPER_INPUT_MODE=Console"'
                ('"{0}" -NoLogo -NoProfile -NonInteractive -File "{1}" %*' -f $script:WrappersPwsh, $script:WrappersFakeScript)
                'exit /b %errorlevel%'
            ) -join "`r`n"
            [IO.File]::WriteAllText($nativePath, $native + "`r`n", [Text.Encoding]::ASCII)
            New-WrapperScripts -CliPath $nativePath
        }

        $result = Invoke-WrapperProcess -ScriptName 'Search-Notes.ps1' -Parameters @{ Text = 'offline exit check' } -FakeExitCode $Code
        $result.ExitCode | Should -Be $Code -Because $result.Stderr
        $result.Stderr | Should -BeNullOrEmpty
        $result.Receipt.Tool | Should -BeExactly 'Search-Notes'
        if ($CliKind -eq 'script') {
            (ConvertFrom-Json -InputObject $result.Receipt.Payload -AsHashtable).Text | Should -BeExactly 'offline exit check'
        }
        (ConvertFrom-Json -InputObject $result.Stdout -AsHashtable).Tool | Should -BeExactly 'Search-Notes'
    }

    It 'serializes typed per-tool named parameters without allowing a Tool field to change routing' {
        $parameters = @{
            Text = "Named 雪 `"quotes`" and O'Brien"
            Count = 0
            Enabled = $false
            Items = @('a', '雪')
            Options = @{ Nested = @{ Enabled = $true }; Empty = @() }
            Tool = 'a payload value, not the selected MCP tool'
        }

        $result = Invoke-WrapperProcess -ScriptName 'Search-Notes.ps1' -Parameters $parameters
        Assert-WrapperReceipt $result
        $actual = ConvertFrom-Json -InputObject $result.Receipt.Payload -AsHashtable -Depth 100
        $actual.Keys.Count | Should -Be $parameters.Keys.Count -Because ('fake CLI payload was: ' + $result.Receipt.Payload)
        $actual.Text | Should -BeExactly $parameters.Text -Because ('fake CLI payload was: ' + $result.Receipt.Payload)
        $actual.Count | Should -Be 0
        $actual.Enabled | Should -BeFalse
        $actual.Items.Count | Should -Be 2
        $actual.Items[1] | Should -BeExactly '雪'
        $actual.Options.Nested.Enabled | Should -BeTrue
        $actual.Options.Empty.Count | Should -Be 0
        $actual.Tool | Should -BeExactly $parameters.Tool
    }

    It 'forwards per-tool <Source> rather than synthesizing a named-parameter payload' -ForEach @(
        @{ Source = 'Json' }
        @{ Source = 'JsonPath' }
    ) {
        $json = '{"explicit":"雪 with \"quotes\"","items":[1,2],"nested":{"ok":true}}'
        $parameters = @{ Text = 'must not leak into explicit JSON' }
        if ($Source -eq 'Json') {
            $parameters.Json = $json
        }
        else {
            $jsonPath = Join-Path $script:WrappersCase 'explicit payload.json'
            [IO.File]::WriteAllText($jsonPath, $json, $script:WrappersUtf8)
            $parameters.JsonPath = $jsonPath
        }

        $result = Invoke-WrapperProcess -ScriptName 'Search-Notes.ps1' -Parameters $parameters
        Assert-WrapperReceipt $result
        $actual = ConvertFrom-Json -InputObject $result.Receipt.Payload -AsHashtable -Depth 100
        $actual.explicit | Should -BeExactly '雪 with "quotes"'
        $actual.items.Count | Should -Be 2
        $actual.nested.ok | Should -BeTrue
        $actual.ContainsKey('Text') | Should -BeFalse
    }

    It 'skips invalid tool and parameter names while preserving reserved JSON inputs' {
        $metadata = @(
            [pscustomobject]@{ Name = '_valid-tool'; Parameters = @('Text', 'text', 'Json', 'json', 'JsonPath', 'JSONPATH', 'PSBoundParameters', 'PSScriptRoot', 'PSCommandPath', 'args', 'input', 'null', 'true', 'false', 'HOME', 'PID', 'Host', 'Error', 'ExecutionContext', 'PSVersionTable', 'bad-name', 'with space', '9startsWithDigit', '') }
            [pscustomobject]@{ Name = '../escape'; Parameters = @() }
            [pscustomobject]@{ Name = 'bad/name'; Parameters = @() }
            [pscustomobject]@{ Name = 'with space'; Parameters = @() }
            [pscustomobject]@{ Name = '9startsWithDigit'; Parameters = @() }
            [pscustomobject]@{ Name = ''; Parameters = @() }
        )
        New-WrapperScripts -ToolMetadata $metadata
        $files = @(Get-ChildItem -LiteralPath $script:WrappersScripts -File | Sort-Object Name | ForEach-Object Name)
        $files.Count | Should -Be 2
        $files | Should -Contain 'Invoke-Tool.ps1'
        $files | Should -Contain '_valid-tool.ps1'
        Test-Path -LiteralPath (Join-Path $script:WrappersCase 'escape.ps1') | Should -BeFalse

        $tokens = $null
        $errors = $null
        $ast = [Management.Automation.Language.Parser]::ParseFile((Join-Path $script:WrappersScripts '_valid-tool.ps1'), [ref]$tokens, [ref]$errors)
        $errors.Count | Should -Be 0
        $parameterNames = @($ast.ParamBlock.Parameters | ForEach-Object { $_.Name.VariablePath.UserPath })
        $parameterNames.Count | Should -Be 3
        $parameterNames | Should -Contain 'Json'
        $parameterNames | Should -Contain 'JsonPath'
        $parameterNames | Should -Contain 'Text'

        $result = Invoke-WrapperProcess -ScriptName '_valid-tool.ps1' -Parameters @{ Json = '{"reserved":"works"}' }
        Assert-WrapperReceipt $result -Tool '_valid-tool'
        (ConvertFrom-Json -InputObject $result.Receipt.Payload -AsHashtable).reserved | Should -BeExactly 'works'
    }

    It 'does not overwrite the generic runner for a discovered tool named Invoke-Tool' {
        New-WrapperScripts -ToolMetadata @(
            [pscustomobject]@{ Name = 'Invoke-Tool'; Parameters = @('Tool', 'Text') }
            [pscustomobject]@{ Name = 'invoke-tool'; Parameters = @('Tool', 'Text') }
        )
        $tokens = $null
        $errors = $null
        $runnerAst = [Management.Automation.Language.Parser]::ParseFile((Join-Path $script:WrappersScripts 'Invoke-Tool.ps1'), [ref]$tokens, [ref]$errors)
        $errors.Count | Should -Be 0
        $parameterNames = @($runnerAst.ParamBlock.Parameters | ForEach-Object { $_.Name.VariablePath.UserPath })
        # Check this before execution: an overwritten runner recursively invokes
        # itself. Never let that known collision hang or terminate the test host.
        $parameterNames | Should -Contain 'ConfigPath' -Because 'Invoke-Tool.ps1 must remain the generic runner, including for case-insensitive filename collisions'
        $parameterNames | Should -Contain 'CliPath'

        $result = Invoke-WrapperProcess -Parameters @{ Tool = 'Invoke-Tool'; Json = '{"Tool":"payload tool","Text":"safe generic dispatch"}' }
        Assert-WrapperReceipt $result -Tool 'Invoke-Tool'
        $actual = ConvertFrom-Json -InputObject $result.Receipt.Payload -AsHashtable
        $actual.Tool | Should -BeExactly 'payload tool'
        $actual.Text | Should -BeExactly 'safe generic dispatch'
    }
}
